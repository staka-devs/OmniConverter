# 配布用の tar にはサブモジュールが無いので、依存はすべて自前でビルドしたものを使う
for dep in highway brotli lcms2 libpng libjpeg; do need $dep; done
fetch libjxl "$LIBJXL_URL" "$LIBJXL_SHA256"
cmake_build "$SRC/libjxl" -DBUILD_TESTING=OFF -DJPEGXL_ENABLE_TOOLS=OFF -DJPEGXL_ENABLE_DOXYGEN=OFF \
    -DJPEGXL_ENABLE_MANPAGES=OFF -DJPEGXL_ENABLE_BENCHMARK=OFF -DJPEGXL_ENABLE_EXAMPLES=OFF -DJPEGXL_ENABLE_JNI=OFF \
    -DJPEGXL_ENABLE_SJPEG=OFF -DJPEGXL_ENABLE_OPENEXR=OFF -DJPEGXL_ENABLE_SKCMS=OFF -DJPEGXL_ENABLE_JPEGLI=OFF \
    -DJPEGXL_ENABLE_PLUGINS=OFF -DJPEGXL_FORCE_SYSTEM_BROTLI=ON -DJPEGXL_FORCE_SYSTEM_HWY=ON -DJPEGXL_FORCE_SYSTEM_LCMS2=ON \
    -DJPEGXL_BUNDLE_LIBPNG=OFF -DJPEGXL_STATIC=OFF
